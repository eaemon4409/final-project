import { ComparisonResult, PageSnapshot } from '../../models/types';

/**
 * Format comparison data into clean markdown and copy to system clipboard.
 */
export async function copyComparisonToClipboard(
  result: ComparisonResult,
  pages: PageSnapshot[]
): Promise<boolean> {
  const pageMap = new Map(pages.map((p) => [p.id, p]));
  const itemMap = new Map(result.items.map((it) => [it.id, it.displayName]));

  let text = `# ${result.comparisonTitle}\n`;
  text += `Category: ${result.comparisonType}\n`;
  if (result.goal) {
    text += `User Goal: ${result.goal}\n`;
  }
  text += '\n';

  // Best overall
  text += '## Quick Verdict\n';
  const winnerName = result.bestOverall.itemId ? (itemMap.get(result.bestOverall.itemId) || result.bestOverall.itemId) : 'No clear winner';
  text += `**Best Overall:** ${winnerName}\n`;
  text += `${result.bestOverall.reason}\n\n`;

  // Comparison Table in Markdown
  text += '## Comparison Table\n\n';
  const headerCols = ['Feature', ...result.items.map((i) => i.displayName)];
  text += `| ${headerCols.join(' | ')} |\n`;
  text += `| ${headerCols.map(() => '---').join(' | ')} |\n`;

  for (const criterion of result.criteria) {
    const valMap = new Map(criterion.values.map((v) => [v.itemId, v.value]));
    const row = [
      criterion.name,
      ...result.items.map((it) => valMap.get(it.id) || 'Not stated'),
    ];
    text += `| ${row.join(' | ')} |\n`;
  }
  text += '\n';

  // Best For
  if (result.bestFor.length > 0) {
    text += '## Best For\n';
    for (const bf of result.bestFor) {
      const name = itemMap.get(bf.itemId) || bf.itemId;
      text += `- **${bf.label}**: ${name} — ${bf.reason}\n`;
    }
    text += '\n';
  }

  // Key Differences
  if (result.keyDifferences.length > 0) {
    text += '## Key Differences\n';
    for (const diff of result.keyDifferences) {
      text += `- ${diff}\n`;
    }
    text += '\n';
  }

  // Missing Information
  if (result.missingInformation.length > 0) {
    text += '## Missing Information\n';
    for (const mi of result.missingInformation) {
      const name = itemMap.get(mi.itemId) || mi.itemId;
      text += `- **${name}**: ${mi.fields.join(', ') || 'None'}\n`;
    }
    text += '\n';
  }

  // Sources
  text += '## Sources\n';
  for (const item of result.items) {
    const page = pageMap.get(item.id);
    if (page) {
      text += `- ${item.displayName}: ${page.url}\n`;
    }
  }
  text += '\n---\n*Generated by Compare Anything — AI Web Comparison Extension*';

  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
    // Fallback for document copy
    const textarea = document.createElement('textarea');
    textarea.value = text;
    document.body.appendChild(textarea);
    textarea.select();
    document.execCommand('copy');
    document.body.removeChild(textarea);
    return true;
  } catch {
    return false;
  }
}

/**
 * Generate and trigger CSV download of the side-by-side comparison.
 */
export function downloadCsv(result: ComparisonResult, pages: PageSnapshot[]): void {
  const itemNames = result.items.map((it) => it.displayName);
  const escapeCsv = (val: string) => `"${(val || '').replace(/"/g, '""')}"`;

  const headers = ['Criterion', 'Importance', ...itemNames, 'Winner(s)'];
  const rows: string[] = [headers.map(escapeCsv).join(',')];

  for (const criterion of result.criteria) {
    const valMap = new Map(criterion.values.map((v) => [v.itemId, v.value]));
    const winners = criterion.winnerItemIds
      .map((id) => result.items.find((it) => it.id === id)?.displayName || id)
      .join(', ') || 'None';

    const row = [
      criterion.name,
      criterion.importance.toUpperCase(),
      ...result.items.map((it) => valMap.get(it.id) || 'Not stated'),
      winners,
    ];
    rows.push(row.map(escapeCsv).join(','));
  }

  // Add Best Overall row
  const bestOverallName = result.bestOverall.itemId
    ? result.items.find((it) => it.id === result.bestOverall.itemId)?.displayName || result.bestOverall.itemId
    : 'No clear winner';
  rows.push('');
  rows.push(['BEST OVERALL', '', bestOverallName, escapeCsv(result.bestOverall.reason)].map(escapeCsv).join(','));

  const csvContent = 'data:text/csv;charset=utf-8,\uFEFF' + encodeURIComponent(rows.join('\r\n'));
  const link = document.createElement('a');
  const safeTitle = result.comparisonTitle.toLowerCase().replace(/[^a-z0-9]+/g, '_') || 'comparison';
  link.setAttribute('href', csvContent);
  link.setAttribute('download', `${safeTitle}_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
